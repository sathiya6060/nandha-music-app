const FILLED = new Set(['play', 'pause', 'next', 'prev'])

export default function Icon({ name, size = 24 }) {
  const paths = PATHS[name]
  if (!paths) return null
  return <Svg size={size} filled={FILLED.has(name)}>{paths}</Svg>
}

/** Heart that renders filled when `filled` is true (liked state). */
export function HeartIcon({ size = 24, filled = false }) {
  return (
    <Svg size={size} filled={filled}>
      {PATHS.heart}
    </Svg>
  )
}
